// EvidenceRun is the outcome of checking a tenant's controls against a compliance framework.
type EvidenceRun struct {
	ID          string              `json:"id,omitempty"`
	TenantID    string              `json:"tenant_id,omitempty"`
	Framework   ComplianceFramework `json:"framework,omitempty"`
	GeneratedAt time.Time           `json:"generated_at,omitzero"`
	// Actor user ID; null when generated by a system or API-key actor.
	GeneratedBy string `json:"generated_by,omitempty"`
	PassCount   int    `json:"pass_count"`
	FailCount   int    `json:"fail_count"`
	NaCount     int    `json:"na_count"`
	// Per-control results; present on GetRun, omitted on ListRuns.
	Controls []EvidenceControlResult `json:"controls,omitempty"`
}

// ComplianceFramework is a string enumeration used by EvidenceRun.Framework.
type ComplianceFramework string

// Values of ComplianceFramework. The server may add values; handle an unknown one gracefully.
const (
	ComplianceFrameworkSOC2     ComplianceFramework = "soc2"
	ComplianceFrameworkIso27001 ComplianceFramework = "iso27001"
)

// EvidenceControlResult is one element of EvidenceRun.Controls. Outcome of a single compliance control
// check against live system state.
type EvidenceControlResult struct {
	// Unique control identifier within the framework (e.g. CC6.1-MFA).
	ID       string `json:"id,omitempty"`
	Name     string `json:"name,omitempty"`
	Category string `json:"category,omitempty"`
	// Framework reference code (e.g. CC6.1, or A.8.5 in ISO/IEC 27001:2022 Annex A).
	Criteria string `json:"criteria,omitempty"`
	// An ISO control's ISO/IEC 27001:2013 Annex A reference (e.g. A.9.4), for audits still on that
	// revision; absent for SOC 2.
	Criteria2013 string `json:"criteria_2013,omitempty"`
	// pass — condition positively confirmed; fail — condition not met; na — data not determinable (never
	// a fabricated pass).
	Status EvidenceControlStatus `json:"status,omitempty"`
	// Human-readable explanation of what was found, in English; always populated.
	Detail string `json:"detail,omitempty"`
	// What was found as a code, such as password_length.too_short, for a console to word itself with
	// params.
	DetailCode string `json:"detail_code,omitempty"`
	// The values the finding is about, such as {min_length, required}.
	Params map[string]any `json:"params,omitempty"`
	// On a failing control, what would make it pass, as a code, such as raise_password_min_length.
	Remedy string `json:"remedy,omitempty"`
	// On a failing control, when it started failing, carried from run to run while it keeps failing.
	FailingSince time.Time    `json:"failing_since,omitzero"`
	Owner        ControlOwner `json:"owner,omitzero"`
}

// EvidenceControlStatus is a string enumeration used by EvidenceControlResult.Status. pass — condition
// positively confirmed; fail — condition not met; na — data not determinable (never a fabricated
// pass).
type EvidenceControlStatus string

// Values of EvidenceControlStatus. The server may add values; handle an unknown one gracefully.
const (
	EvidenceControlStatusPass EvidenceControlStatus = "pass"
	EvidenceControlStatusFail EvidenceControlStatus = "fail"
	EvidenceControlStatusNa   EvidenceControlStatus = "na"
)

// ControlOwner is the person the organisation has made answer for a control, as it is now.
type ControlOwner struct {
	ControlID   string    `json:"control_id,omitempty"`
	UserID      string    `json:"user_id,omitempty"`
	Email       string    `json:"email,omitempty"`
	DisplayName string    `json:"display_name,omitempty"`
	UpdatedAt   time.Time `json:"updated_at,omitzero"`
}

